type PdfSection = {
  title: string
  lines: string[]
}

export async function exportStudentToolPdf(title: string, sections: PdfSection[]) {
  if ([title, ...sections.flatMap(section => [section.title, ...section.lines])].join("").split("").some(character => character.charCodeAt(0) > 127)) {
    const popup = window.open("", "_blank")
    if (!popup) throw new Error("Allow pop-ups to export this document")
    popup.opener = null
    const escape = (value: string) => value.replace(/[&<>"']/g, character => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]!)
    popup.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${escape(title)}</title><style>body{font:14px/1.5 system-ui,sans-serif;max-width:800px;margin:32px auto}h1{font-size:24px}h2{font-size:18px;margin-top:24px}p{white-space:pre-wrap}@media print{body{margin:12mm}}</style></head><body><h1>${escape(title)}</h1><p>Generated by UniChase on ${escape(new Date().toLocaleDateString())}</p>${sections.map(section => `<h2>${escape(section.title)}</h2>${section.lines.map(line => `<p>${escape(line)}</p>`).join("")}`).join("")}</body></html>`)
    popup.document.close()
    popup.addEventListener("load", () => popup.print(), { once: true })
    return
  }
  const { default: jsPDF } = await import("jspdf")
  const doc = new jsPDF()
  const margin = 16
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  let y = 20

  doc.setFont("helvetica", "bold")
  doc.setFontSize(18)
  doc.text(doc.splitTextToSize(title, pageWidth - margin * 2), margin, y)
  y += 10

  doc.setFont("helvetica", "normal")
  doc.setFontSize(10)
  doc.text(`Generated by UniChase on ${new Date().toLocaleDateString()}`, margin, y)
  y += 12

  sections.forEach((section) => {
    if (y > pageHeight - 30) {
      doc.addPage()
      y = 20
    }

    doc.setFont("helvetica", "bold")
    doc.setFontSize(13)
    doc.text(section.title, margin, y)
    y += 7

    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)

    section.lines.forEach((line) => {
      const wrapped = doc.splitTextToSize(line, pageWidth - margin * 2)
      wrapped.forEach((part: string) => {
        if (y > pageHeight - 18) {
          doc.addPage()
          y = 20
        }

        doc.text(part, margin, y)
        y += 6
      })
    })

    y += 5
  })

  doc.save(`${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "unichase"}.pdf`)
}
